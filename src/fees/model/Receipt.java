package fees.model;

import java.text.SimpleDateFormat;
import java.util.Date;

/**
 * Unit 1 Syllabus Concept: Class Receipt; Math class; StringBuffer for receipts
 * Corresponds to Database Table: receipts
 */
public class Receipt {

    private int receiptId;
    private String receiptNo;
    private String studentId;
    private String studentName;
    private double amountPaid;
    private String paymentType;     // Tuition / Transport / Exam / Lump-Sum
    private String paymentDate;
    private String paymentMode;     // Cash / Card / UPI / NetBanking / Cheque
    private String remarks;
    private String receiptText;

    public Receipt() {
    }

    public Receipt(int receiptId, String receiptNo, String studentId, String studentName,
                   double amountPaid, String paymentType, String paymentDate,
                   String paymentMode, String remarks) {
        this.receiptId = receiptId;
        this.receiptNo = receiptNo;
        this.studentId = studentId;
        this.studentName = studentName;
        this.amountPaid = Fee.roundAmount(amountPaid);
        this.paymentType = paymentType;
        this.paymentDate = (paymentDate != null && !paymentDate.isEmpty()) ?
                paymentDate : new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date());
        this.paymentMode = paymentMode;
        this.remarks = (remarks != null && !remarks.isEmpty()) ? remarks : "Fee installment processed successfully.";
        this.receiptText = generateReceiptStringBuffer(0.0);
    }

    /**
     * Unit 1 Syllabus Requirement: StringBuffer for receipts.
     * Builds a structured, beautiful receipt using java.lang.StringBuffer and Math methods.
     *
     * @param remainingPendingDue current pending fee balance after payment
     * @return formatted receipt string
     */
    public String generateReceiptStringBuffer(double remainingPendingDue) {
        // Unit 1 Concept: StringBuffer for receipts
        StringBuffer sb = new StringBuffer(1024);

        // Unit 1 Math class: generate verification code and round values
        long verificationToken = Math.round(Math.random() * 899999.0) + 100000L;
        double roundedPaid = Fee.roundAmount(this.amountPaid);
        double clampedDue = Math.max(0.0, Fee.roundAmount(remainingPendingDue));

        sb.append("======================================================================\n");
        sb.append("                   DELHI PUBLIC INTERNATIONAL SCHOOL                  \n");
        sb.append("                    OFFICIAL FEE PAYMENT RECEIPT                      \n");
        sb.append("         Affiliated to CBSE | System Generated Cash Receipt           \n");
        sb.append("======================================================================\n");
        sb.append(String.format(" Receipt Number  : %-20s  Date & Time : %s\n", receiptNo, paymentDate));
        sb.append(String.format(" Auth Token Code : SEC-%06d           Payment Mode: %s\n", verificationToken, paymentMode));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" Student UID     : %-20s  Student Name: %s\n", studentId, studentName));
        sb.append(String.format(" Fee Category    : %-20s  Status      : %s\n", paymentType, "PAID / CLEARED"));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" %-42s | %18s\n", "FEE HEAD / PARTICULARS", "AMOUNT (INR)"));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" Base Installment Deposited (%-14s) | Rs. %15.2f\n", paymentType, roundedPaid));
        sb.append(String.format(" Surcharge / Processing Charges              | Rs. %15.2f\n", 0.00));
        sb.append(String.format(" Concession / Scholarship Applied            | Rs. %15.2f\n", 0.00));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" NET TOTAL AMOUNT PAID                       | Rs. %15.2f\n", roundedPaid));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" REMAINING PENDING DUES                      | Rs. %15.2f\n", clampedDue));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(String.format(" Remarks: %s\n", remarks));
        sb.append("----------------------------------------------------------------------\n");
        sb.append(" * This is a computer-generated receipt and requires no physical signature.\n");
        sb.append(" * Generated by Group 15 School Fee Management System (CSE2003 Java).\n");
        sb.append("======================================================================\n");

        this.receiptText = sb.toString();
        return this.receiptText;
    }

    // Getters and Setters
    public int getReceiptId() { return receiptId; }
    public void setReceiptId(int receiptId) { this.receiptId = receiptId; }

    public String getReceiptNo() { return receiptNo; }
    public void setReceiptNo(String receiptNo) { this.receiptNo = receiptNo; }

    public String getStudentId() { return studentId; }
    public void setStudentId(String studentId) { this.studentId = studentId; }

    public String getStudentName() { return studentName; }
    public void setStudentName(String studentName) { this.studentName = studentName; }

    public double getAmountPaid() { return amountPaid; }
    public void setAmountPaid(double amountPaid) { this.amountPaid = Fee.roundAmount(amountPaid); }

    public String getPaymentType() { return paymentType; }
    public void setPaymentType(String paymentType) { this.paymentType = paymentType; }

    public String getPaymentDate() { return paymentDate; }
    public void setPaymentDate(String paymentDate) { this.paymentDate = paymentDate; }

    public String getPaymentMode() { return paymentMode; }
    public void setPaymentMode(String paymentMode) { this.paymentMode = paymentMode; }

    public String getRemarks() { return remarks; }
    public void setRemarks(String remarks) { this.remarks = remarks; }

    public String getReceiptText() { return receiptText; }
    public void setReceiptText(String receiptText) { this.receiptText = receiptText; }
}
